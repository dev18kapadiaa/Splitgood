def get_currency_symbol(code):
    return CURRENCY_SYMBOLS.get(code, code)


def format_currency(amount, code):
    symbol = get_currency_symbol(code)
    formatted_amount = abs(amount)
    sign = '-' if amount < 0 else ''
    return f'{sign}{symbol}{formatted_amount:,.2f}'


def format_multi_currency_balance(currency_map):
    """Format multi-currency balance with proper RTL symbol handling.
    
    Returns a string like: '-₹12.00 - د.إ20.00 + $30.00'
    Properly handles RTL currencies like AED (د.إ) by separating sign from symbol.
    """
    if not currency_map:
        return '$0.00'

    parts = []
    for code, amount in sorted(currency_map.items()):
        if amount == 0:
            continue
        symbol = get_currency_symbol(code)
        amount_val = float(amount)
        is_positive = amount_val > 0
        formatted_str = f'{symbol}{abs(amount_val):,.2f}'
        parts.append((is_positive, formatted_str))

    if not parts:
        return '$0.00'

    result_components = []
    for i, (is_positive, formatted_str) in enumerate(parts):
        if i == 0:
            sign = '+' if is_positive else '-'
            result_components.append(f'{sign}{formatted_str}')
        else:
            separator = '+' if is_positive else '-'
            result_components.append(f'{separator}{formatted_str}')
    
    result = result_components[0]
    for component in result_components[1:]:
        result += f' {component}'
    
    return result


def format_multi_currency_additive(currency_map):
    """Format a channel map as additive terms only (no +/- signs).

    Example: {'AED': 25, 'USD': 10} -> 'AED25.00 + $10.00'
    """
    if not currency_map:
        return '$0.00'

    parts = []
    for code, amount in sorted(currency_map.items()):
        if amount == 0:
            continue
        symbol = get_currency_symbol(code)
        amount_val = abs(float(amount))
        parts.append(f'{symbol}{amount_val:,.2f}')

    if not parts:
        return '$0.00'

    return ' + '.join(parts)
